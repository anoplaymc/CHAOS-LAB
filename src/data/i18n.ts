export function translate(lang: Lang, key: string, params?: Record<string, string | number>): string {
  const e = D[key];
  let s = e ? e[lang === 'ru' ? 1 : 0] : key;
  if (params) for (const k in params) s = s.replace(`{${k}}`, String(params[k]));
  return s;
}

